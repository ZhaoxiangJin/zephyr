#define EBPF_OP_MUL64_REG	(EBPF_CLS_ALU64 | EBPF_ALU_MUL | EBPF_SRC_REG)
#define EBPF_OP_DIV64_IMM	(EBPF_CLS_ALU64 | EBPF_ALU_DIV | EBPF_SRC_IMM)
#define EBPF_OP_DIV64_REG	(EBPF_CLS_ALU64 | EBPF_ALU_DIV | EBPF_SRC_REG)
