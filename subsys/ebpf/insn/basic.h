#define EBPF_JMP_JLE		0xB0U
#define EBPF_JMP_CALL		0x80U
#define EBPF_JMP_EXIT		0x90U

#define EBPF_SIZE_W		0x00U
#define EBPF_SIZE_H		0x08U
#define EBPF_SIZE_B		0x10U
#define EBPF_SIZE_DW		0x18U

#define EBPF_MODE_IMM		0x00U
